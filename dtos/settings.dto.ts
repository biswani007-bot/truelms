import { z } from "zod";

export const SettingsUpdateSchema = z.object({
  org: z.object({
    orgName: z.string().min(1, "Org name is required"),
    legalName: z.string().min(1, "Legal name is required"),
    logo: z.string().optional().default(""),
    darkLogo: z.string().optional().default(""),
    favicon: z.string().optional().default(""),
    supportEmail: z.string().email("Invalid support email"),
    supportPhone: z.string().min(1, "Support phone is required"),
    website: z.string().url("Invalid website URL"),
    address: z.string().min(1, "Address is required"),
    city: z.string().min(1, "City is required"),
    state: z.string().min(1, "State is required"),
    country: z.string().min(1, "Country is required"),
    postalCode: z.string().min(1, "Postal code is required"),
  }),
  branding: z.object({
    primaryColor: z.string().regex(/^#([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3})$/, "Invalid Hex color"),
    secondaryColor: z.string().regex(/^#([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3})$/, "Invalid Hex color"),
    accentColor: z.string().regex(/^#([A-Fa-f0-9]{6}|[A-Fa-f0-9]{3})$/, "Invalid Hex color"),
    typography: z.string().default("Inter"),
    defaultTheme: z.enum(["light", "dark", "system"]).default("dark"),
    emailBranding: z.string().optional().default(""),
    invoiceBranding: z.string().optional().default(""),
    certificateBranding: z.string().optional().default(""),
  }),
  academic: z.object({
    defaultCourseStatus: z.enum(["DRAFT", "ACTIVE", "ARCHIVED"]).default("DRAFT"),
    enrollmentPolicy: z.string().default("open"),
    certificatePolicy: z.string().default("standard"),
    passingPercentage: z.number().min(0).max(100).default(80),
    attendanceRequirement: z.number().min(0).max(100).default(75),
    courseVisibility: z.enum(["PUBLIC", "PRIVATE"]).default("PUBLIC"),
    defaultInstructorAssignment: z.string().optional().default(""),
  }),
  certificate: z.object({
    attendanceThreshold: z.number().min(0).max(100).default(80),
    assignmentSubmissionThreshold: z.number().min(0).max(100).default(75),
    quizPassingThreshold: z.number().min(0).max(100).default(60),
    syllabusCompletionRequired: z.boolean().default(true),
  }).optional(),
  batch: z.object({
    defaultCapacity: z.number().min(1).max(500).default(50),
    maxCapacity: z.number().min(1).max(1000).default(100),
    waitingListEnabled: z.boolean().default(true),
    autoAllocationEnabled: z.boolean().default(true),
    transferRules: z.string().optional().default("flexible"),
    cancellationRules: z.string().optional().default("standard"),
    enrollmentWindowDays: z.number().min(1).default(14),
    futureCohortRules: z.string().optional().default(""),
  }).refine(data => data.defaultCapacity <= data.maxCapacity, {
    message: "Default capacity cannot exceed maximum capacity",
    path: ["defaultCapacity"]
  }),
  notifications: z.object({
    emailEnabled: z.boolean().default(true),
    smsEnabled: z.boolean().default(false),
    pushEnabled: z.boolean().default(false),
    inAppEnabled: z.boolean().default(true),
    reminderIntervals: z.array(z.number()).default([15, 60]),
    digestSettings: z.string().optional().default("daily"),
  }),
  email: z.object({
    smtpHost: z.string().min(1, "SMTP Host is required"),
    smtpPort: z.number().min(1).default(587),
    smtpUser: z.string().optional().default(""),
    smtpPass: z.string().optional().default(""),
    senderName: z.string().min(1, "Sender name is required"),
    senderEmail: z.string().email("Invalid sender email"),
    replyTo: z.string().email("Invalid reply-to email"),
    templates: z.string().optional().default(""),
  }),
  security: z.object({
    sessionTimeout: z.number().min(60, "Session timeout must be at least 60 seconds"),
    passwordPolicy: z.object({
      minLength: z.number().min(6).default(8),
      requireSpecialChar: z.boolean().default(true),
      requireUppercase: z.boolean().default(true),
    }),
    loginAttempts: z.number().min(1).max(20).default(5),
    accountLockDuration: z.number().min(1).default(15),
    otpSettings: z.object({
      enabled: z.boolean().default(false),
      expirySeconds: z.number().min(30).default(300),
    }),
    refreshTokenExpiryDays: z.number().min(1).default(7),
    jwtExpiryMinutes: z.number().min(1).default(15),
  }),
  payment: z.object({
    currency: z.string().min(1).default("USD"),
    taxPercentage: z.number().min(0).max(100).default(0),
    invoicePrefix: z.string().min(1).default("INV-"),
    receiptPrefix: z.string().min(1).default("REC-"),
    paymentTerms: z.string().optional().default("immediate"),
    refundPolicyText: z.string().optional().default("Refundable up to 24h before second lecture."),
    enabledPaymentMethods: z.array(z.string()).default([]),
    mode: z.enum(["test", "live"]).default("test"),
    gateways: z.array(z.object({
      provider: z.string(),
      enabled: z.boolean(),
      mode: z.enum(["test", "live"]),
      publicKey: z.string().optional().default(""),
      secretKey: z.string().optional().default("")
    })).default([])
  }),
  storage: z.object({
    r2Bucket: z.string().optional().default(""),
    r2AccountId: z.string().optional().default(""),
    r2AccessKeyId: z.string().optional().default(""),
    r2SecretAccessKey: z.string().optional().default(""),
    allowedFileTypes: z.array(z.string()).default(["image/jpeg", "image/png", "application/pdf"]),
    maxUploadSizeMb: z.number().min(1).default(10),
    imageOptimizationEnabled: z.boolean().default(true),
  }),
  localization: z.object({
    timezone: z.string().min(1).default("UTC"),
    currency: z.string().min(1).default("USD"),
    language: z.string().min(1).default("en"),
    dateFormat: z.string().min(1).default("YYYY-MM-DD"),
    numberFormat: z.string().min(1).default("standard"),
  }),
  platform: z.object({
    featureFlags: z.object({
      AUTHENTICATION: z.boolean().default(true),
      CRM: z.boolean().default(true),
      CMS: z.boolean().default(true),
      STUDENTS: z.boolean().default(true),
      TEACHERS: z.boolean().default(true),
      COURSES: z.boolean().default(true),
      LIVE_CLASSES: z.boolean().default(true),
      ASSIGNMENTS: z.boolean().default(true),
      ASSESSMENTS: z.boolean().default(true),
      PAYMENTS: z.boolean().default(true),
      REPORTS: z.boolean().default(true),
      BATCH_ENGINE: z.boolean().default(true),
      BACK_OFFICE: z.boolean().default(true),
      CERTIFICATES: z.boolean().default(true),
      AI_FEATURES: z.boolean().default(false),
    }),
  }),
  preferences: z.object({
    registrationEnabled: z.boolean().default(true),
    publicCourseVisibility: z.boolean().default(true),
    debugMode: z.boolean().default(false),
    apiRateLimits: z.number().min(1).default(100),
  }),
  maintenance: z.object({
    enabled: z.boolean().default(false),
    message: z.string().optional().default("System is under maintenance. We will be back shortly."),
    estimatedEndTime: z.string().optional().default(""),
    whitelistedIps: z.array(z.string()).default([]),
  }),
  audit: z.object({
    enabled: z.boolean().default(true),
    logLevels: z.array(z.string()).default(["info", "warn", "error"]),
    retainDays: z.number().min(1).default(90),
  }),
});

export type SettingsUpdateInput = z.infer<typeof SettingsUpdateSchema>;
