/* eslint-disable @typescript-eslint/no-explicit-any */
import { Invoice } from "../../models/invoice.model";
import { Receipt } from "../../models/receipt.model";
import { Payment } from "../../models/payment.model";
import { Enrollment } from "../../models/enrollment.model";
import { Student } from "../../models/student.model";
import { User } from "../../models/user.model";
import { Lead } from "../../models/lead.model";
import { EmailService } from "../email/email.service";
import { BusinessEventService } from "../events/business-event.service";
import { AuditService } from "../audit/audit.service";
import { logger } from "../../utils/logger";

export class PaymentAutomationService {
  /**
   * Provider-neutral payment completion handler:
   * 1. Idempotently generate Receipt (if not already generated by PaymentService)
   * 2. Send payment confirmation email
   * 3. Transition Enrollment → confirmed
   * 4. Emit Enrollment.confirmed business event for downstream automation
   */
  static async handlePaymentCompleted(paymentId: string): Promise<any> {
    const payment = await Payment.findById(paymentId).populate("student");
    if (!payment) {
      throw new Error(`Payment ${paymentId} not found`);
    }

    const student = payment.student as any;
    if (!student) {
      throw new Error(`Student not associated with payment ${paymentId}`);
    }

    // 1. Ensure Receipt exists (idempotently check)
    let receipt = await Receipt.findOne({ payment: payment._id });
    if (!receipt) {
      const invoice = await Invoice.findById(payment.invoice);
      if (!invoice) {
        throw new Error(`Invoice not found for payment ${paymentId}`);
      }

      const receiptCount = await Receipt.countDocuments();
      const receiptNumber = `RCP-${String(receiptCount + 1).padStart(6, "0")}`;
      receipt = await Receipt.create({
        receiptNumber,
        invoice: invoice._id,
        payment: payment._id,
        student: student._id,
        enrollment: invoice.enrollment || undefined,
        issueDate: new Date(),
        amount: payment.amount,
        taxes: 0,
      });
      logger.info(`[PaymentAutomation] Issued receipt ${receiptNumber} for payment ${paymentId} (Student: ${student.studentId})`);
    }

    // 2. Send Payment Confirmation Email
    // Student might have user account with verified email
    let recipientEmail = student.email;
    if (!recipientEmail && student.user) {
      const user = await User.findById(student.user);
      if (user?.email) recipientEmail = user.email;
    }
    if (!recipientEmail) {
      recipientEmail = `${student.studentId?.toLowerCase()}@student.truelern.com`;
    }

    try {
      await EmailService.sendMail({
        to: recipientEmail,
        subject: `Payment Receipt: ${receipt.receiptNumber} — TrueLern`,
        html: `
          <div style="font-family: sans-serif; padding: 20px;">
            <h2>Payment Confirmation</h2>
            <p>Dear ${student.firstName},</p>
            <p>Thank you for your payment of <strong>$${(payment.amount / 100).toFixed(2)}</strong>.</p>
            <p>Receipt Number: <strong>${receipt.receiptNumber}</strong></p>
            <p>Payment Date: ${new Date(payment.paymentDate || Date.now()).toLocaleDateString()}</p>
            <p style="margin-top: 20px; color: #6b7280;">Your enrollment is now being processed. You will receive a welcome email shortly with your login details.</p>
          </div>
        `,
      });
    } catch (emailErr: any) {
      logger.warn(
        { err: emailErr?.message, recipient: recipientEmail },
        "[PaymentAutomation] Could not dispatch payment confirmation email"
      );
    }

    // 3. Transition Enrollment from waiting-payment/pending/draft → confirmed (idempotent)
    const invoice = await Invoice.findById(payment.invoice);
    if (invoice && invoice.status !== "paid") {
      const nextOutstanding = Math.max(0, (invoice.outstandingAmount || 0) - payment.amount);
      invoice.outstandingAmount = nextOutstanding;
      if (nextOutstanding <= 0) {
        invoice.status = "paid";
      }
      await invoice.save();
      logger.info(`[PaymentAutomation] Reconciled invoice ${invoice.invoiceNumber}: status ${invoice.status}`);
    }

    let enrollment = null;
    if (invoice?.enrollment) {
      enrollment = await Enrollment.findById(invoice.enrollment);
    }

    // Gap Fix: If invoice was not pre-linked to an enrollment, find existing enrollment for student + course
    if (!enrollment && invoice?.course && student?._id) {
      enrollment = await Enrollment.findOne({
        student: student._id,
        course: invoice.course,
        isDeleted: { $ne: true },
      });
      if (enrollment && !invoice.enrollment) {
        invoice.enrollment = enrollment._id as any;
        await invoice.save();
      }
    }

    // If still no enrollment exists for student + course, create one authoritatively
    if (!enrollment && invoice?.course && student?._id) {
      const enrollmentCount = await Enrollment.countDocuments();
      const enrollmentNumber = `ENR-${String(enrollmentCount + 1).padStart(6, "0")}`;
      enrollment = await Enrollment.create({
        enrollmentNumber,
        student: student._id,
        course: invoice.course,
        academicSession: new Date().getFullYear().toString(),
        enrollmentDate: new Date(),
        status: "waiting-payment",
      });
      invoice.enrollment = enrollment._id as any;
      await invoice.save();
      logger.info(`[PaymentAutomation] Created and linked missing enrollment ${enrollmentNumber} for invoice ${invoice.invoiceNumber}`);
    }

    if (enrollment) {
      const payableStatuses = ["waiting-payment", "pending", "draft", "approved"];
      if (payableStatuses.includes(enrollment.status)) {
        enrollment.status = "confirmed";
        await enrollment.save();

        logger.info(`[PaymentAutomation] Enrollment ${enrollment.enrollmentNumber} transitioned to confirmed`);

        // Update associated CRM Lead to enrolled (Phase 3J, 3Q)
        if (enrollment.lead) {
          await Lead.findByIdAndUpdate(enrollment.lead, { status: "enrolled" });
          logger.info(`[PaymentAutomation] Lead ${enrollment.lead} transitioned to enrolled`);
        } else if (enrollment.student) {
          const matchedLead = await Lead.findOneAndUpdate(
            { student: enrollment.student, status: { $in: ["demo_completed", "enrollment_pending", "application_submitted", "qualified", "new"] } },
            { status: "enrolled" }
          );
          if (matchedLead) {
            logger.info(`[PaymentAutomation] Lead ${matchedLead._id} transitioned to enrolled`);
          }
        }

        // 4. Emit Enrollment.confirmed event → triggers student provisioning + batch allocation
        await BusinessEventService.publishEvent({
          eventType: "Enrollment.confirmed",
          entityType: "Enrollment",
          entityId: enrollment._id.toString(),
          payload: {
            enrollmentId: enrollment._id.toString(),
            studentId: student._id.toString(),
            courseId: enrollment.course.toString(),
          },
          idempotencyKey: `enrollment-confirmed-${enrollment._id}`,
        });

        // Direct execution of student provisioning + batch allocation for immediate confirmation
        try {
          const { EnrollmentAutomationService } = await import("./enrollment-automation.service");
          await EnrollmentAutomationService.handleEnrollmentConfirmed(enrollment._id.toString());
        } catch (provErr: any) {
          logger.warn(`[PaymentAutomation] Direct student batch provisioning notice: ${provErr.message}`);
        }

        // Audit trail
        await AuditService.logMutation({
          action: "enrollment.confirmed-via-payment",
          entity: "Enrollment",
          entityId: enrollment._id.toString(),
          metadata: {
            paymentId: payment._id.toString(),
            receiptNumber: receipt.receiptNumber,
            amount: payment.amount,
          },
        });
      } else {
        logger.info(`[PaymentAutomation] Enrollment ${enrollment.enrollmentNumber} already in active/post-confirmation status (${enrollment.status})`);
      }
    }

    return {
      receiptId: receipt._id,
      receiptNumber: receipt.receiptNumber,
      amount: payment.amount,
    };
  }
}
