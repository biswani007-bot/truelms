/* eslint-disable @typescript-eslint/no-explicit-any */
import React from "react";
import Link from "next/link";
import { reportSnapshotRepository } from "../../../../../repositories/report-snapshot.repository";
import { connectDB } from "../../../../../config/db";

export const revalidate = 0;

export default async function SnapshotsPage() {
  await connectDB();

  const snapshots = await reportSnapshotRepository.findMany({}, { populate: ["generatedBy"] });

  return (
    <div className="flex flex-col gap-10">
      {/* Header */}
      <div className="flex justify-between items-start">
        <div>
          <h1 className="text-2xl font-extrabold text-gray-900">Report Snapshots</h1>
          <p className="text-sm text-gray-500 mt-1">
            Browse captured point-in-time snapshots and historic KPI metrics.
          </p>
        </div>
        <Link
          href="/admin/reports"
          className="px-4 py-2 border border-gray-200 text-gray-600 hover:bg-white hover:text-white rounded-lg text-sm transition"
        >
          ← Dashboard
        </Link>
      </div>

      {/* Snapshots Ledger */}
      <div className="bg-gray-50 border border-gray-200 rounded-2xl overflow-hidden">
        <div className="px-6 py-4 border-b border-gray-200 flex justify-between items-center">
          <h2 className="text-base font-bold text-gray-900">Historic KPI Captures</h2>
          <span className="text-xs text-gray-400">{snapshots.length} snapshots</span>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-gray-200 text-xs text-gray-400 uppercase tracking-wider">
                <th className="text-left px-6 py-3">Snapshot Name</th>
                <th className="text-left px-6 py-3">Type</th>
                <th className="text-left px-6 py-3">Reference Date</th>
                <th className="text-left px-6 py-3">Academic Session</th>
                <th className="text-left px-6 py-3">Generated By</th>
                <th className="text-left px-6 py-3">Captured Date</th>
              </tr>
            </thead>
            <tbody>
              {snapshots.map((snap) => {
                const userObj = snap.generatedBy as any;
                return (
                  <tr key={snap._id?.toString()} className="border-b border-slate-850 hover:bg-white transition">
                    <td className="px-6 py-4 text-gray-900 font-medium text-sm">{snap.name}</td>
                    <td className="px-6 py-4">
                      <span className="px-2 py-0.5 rounded text-[10px] font-bold uppercase bg-white text-indigo-600 border border-indigo-200">
                        {snap.snapshotType}
                      </span>
                    </td>
                    <td className="px-6 py-4 text-gray-500 text-xs">
                      {new Date(snap.referenceDate).toLocaleDateString()}
                    </td>
                    <td className="px-6 py-4 text-gray-500 font-mono text-xs">{snap.academicSession || "N/A"}</td>
                    <td className="px-6 py-4 text-gray-500 text-xs">
                      {userObj ? `${userObj.firstName} ${userObj.lastName}` : "System"}
                    </td>
                    <td className="px-6 py-4 text-gray-500 text-xs">
                      {new Date((snap as any).createdAt).toLocaleString()}
                    </td>
                  </tr>
                );
              })}
              {snapshots.length === 0 && (
                <tr>
                  <td colSpan={6} className="text-center py-12 text-slate-550 text-xs">No historic snapshots captured.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
